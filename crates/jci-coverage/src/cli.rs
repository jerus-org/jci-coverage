//! # jci-coverage
//!
//! A CLI that adds cyclomatic complexity to a
//! [`cargo-llvm-cov`](https://crates.io/crates/cargo-llvm-cov) coverage report
//! and uploads it to [OtterWise](https://getotterwise.com) for code quality
//! reporting.
//!
//! Two independent subcommands:
//!
//! - **`complexity`** — computes cyclomatic complexity for the Rust functions a
//!   Cobertura or lcov report covers and writes it into the report, which
//!   `cargo llvm-cov` leaves at zero. OtterWise reads it for its Complexity and
//!   CRAP scores. Rust-specific.
//! - **`upload`** — takes a coverage file path and posts it to OtterWise. It
//!   never assumes `complexity` produced the file: a non-Rust project can run
//!   `upload` on its own, standalone, against a coverage report it generated by
//!   whatever means it already uses.
//!
//! The coverage report itself is written by the project's own job
//! (`cargo llvm-cov --lcov`); this tool no longer runs `cargo`.
//!
//! Kept as separate subcommands, not one, so the CLI surface (and OtterWise's
//! field mapping) can grow additional upload targets later without reshaping
//! complexity analysis.

use anyhow::Result;
use clap::{Parser, Subcommand};

use crate::{complexity, upload};

/// Source-based Rust code coverage with OtterWise upload.
#[derive(Debug, Parser)]
#[command(name = "jci-coverage")]
#[command(
    author,
    version,
    about = "Rust code complexity for coverage reports, with OtterWise upload",
    long_about = "Add cyclomatic complexity to a cargo-llvm-cov coverage \
        report, and upload the report to OtterWise for code quality \
        reporting. `complexity` and `upload` are independent: `upload` works \
        standalone against any coverage file, Rust or not.",
    term_width = 70
)]
pub struct Cli {
    #[command(flatten)]
    pub logging: clap_verbosity_flag::Verbosity<clap_verbosity_flag::InfoLevel>,

    #[command(subcommand)]
    command: Commands,
}

#[derive(Debug, Subcommand)]
enum Commands {
    /// Add cyclomatic complexity to a Cobertura or lcov report.
    #[command(
        long_about = "Computes the cyclomatic complexity of the Rust \
            functions a coverage report covers and writes it into each \
            method of a Cobertura report, where OtterWise reads it for its \
            Complexity and CRAP scores. `cargo llvm-cov` leaves every \
            complexity at 0. Takes the Cobertura report of `cargo llvm-cov`, \
            or its lcov report, which is converted first. Reads the source files the report names, relative to \
            `--source-root`, and needs no other tool. Rust only: it refuses \
            a report that is not a `cargo llvm-cov` report of `.rs` files. \
            Run it after `cargo llvm-cov` has written one, and before `upload`.",
        term_width = 70
    )]
    Complexity(complexity::ComplexityArgs),
    /// Upload a coverage report to OtterWise.
    #[command(
        long_about = "Standalone: takes a coverage file path and uploads \
            it. Does not require Rust or `cargo-llvm-cov` — the \
            caller is responsible for the file existing at the given path \
            in a format OtterWise accepts. It must run in CircleCI: \
            OtterWise shows only uploads that carry a CI identity, so \
            without the CircleCI environment it stops and names what \
            is missing.",
        term_width = 70
    )]
    Upload(upload::UploadArgs),
}

impl Cli {
    /// Execute the selected subcommand.
    pub fn run(&self) -> Result<()> {
        match &self.command {
            Commands::Complexity(args) => complexity::run(args),
            Commands::Upload(args) => upload::run(args),
        }
    }
}

#[cfg(test)]
mod tests {
    use std::path::PathBuf;

    use super::*;

    #[test]
    fn the_report_subcommand_is_gone() {
        let err = Cli::try_parse_from(["jci-coverage", "report"]).unwrap_err();
        assert!(err.to_string().contains("unrecognized subcommand"), "{err}");
    }

    #[test]
    fn the_subcommands_are_complexity_and_upload() {
        use clap::CommandFactory;
        let names: Vec<String> = Cli::command()
            .get_subcommands()
            .map(|s| s.get_name().to_string())
            .filter(|n| n != "help")
            .collect();
        assert_eq!(names, ["complexity", "upload"]);
    }

    #[test]
    fn upload_has_no_org_token_flag() {
        let parsed = Cli::try_parse_from([
            "jci-coverage",
            "upload",
            "--file",
            "coverage/lcov.info",
            "--org-token",
            "t",
        ]);
        assert!(parsed.is_err());
    }

    #[test]
    fn upload_requires_file() {
        assert!(Cli::try_parse_from(["jci-coverage", "upload"]).is_err());
        let cli = Cli::try_parse_from(["jci-coverage", "upload", "--file", "coverage/lcov.info"])
            .expect("parses");
        match cli.command {
            Commands::Upload(args) => {
                assert_eq!(args.file, PathBuf::from("coverage/lcov.info"));
            }
            other => panic!("expected Upload, got {other:?}"),
        }
    }

    #[test]
    fn upload_does_not_require_rust_or_complexity_context() {
        // No --package, --runner, or any Rust-only flag exists on upload —
        // it stands alone. This test pins that by asserting such a flag is
        // rejected on upload.
        let err = Cli::try_parse_from([
            "jci-coverage",
            "upload",
            "--file",
            "coverage.out",
            "--runner",
            "test",
        ])
        .unwrap_err();
        assert!(err.to_string().contains("runner"));
    }

    #[test]
    fn parse_complexity_defaults() {
        let cli = Cli::try_parse_from(["jci-coverage", "complexity"]).expect("complexity parses");
        match cli.command {
            Commands::Complexity(args) => {
                assert_eq!(args.file, PathBuf::from("coverage/cobertura.xml"));
                assert_eq!(args.output, None, "the report is annotated in place");
                assert_eq!(args.source_root, PathBuf::from("."));
                assert_eq!(args.duplicates, complexity::Duplicates::Merge);
                assert_eq!(args.rules, complexity::Rules::Rca);
                assert_eq!(args.unmatched, complexity::Unmatched::Keep);
                assert!(!args.no_rollup, "roll-ups are on by default");
                assert!(!args.exclude_tests);
                assert_eq!(args.warn_complexity, 10);
                assert_eq!(args.warn_crap, 30.0);
                assert!(!args.gate_tests);
                assert_eq!(args.max_complexity, 0, "no maximum by default");
                assert_eq!(args.max_crap, 0.0);
                assert_eq!((args.baseline, args.write_baseline), (None, None));
                assert!(!args.check_only);
                assert_eq!(args.summary_file, None);
                assert!(!args.dry_run);
            }
            other => panic!("expected Complexity, got {other:?}"),
        }
    }

    #[test]
    fn parse_complexity_options() {
        let cli = Cli::try_parse_from([
            "jci-coverage",
            "complexity",
            "--file",
            "out/c.xml",
            "--output",
            "out/annotated.xml",
            "--source-root",
            "/work",
            "--duplicates",
            "keep",
            "--rules",
            "mccabe",
            "--unmatched",
            "fail",
            "--no-rollup",
            "--exclude-tests",
            "--dry-run",
        ])
        .expect("complexity parses");
        match cli.command {
            Commands::Complexity(args) => {
                assert_eq!(args.file, PathBuf::from("out/c.xml"));
                assert_eq!(args.output, Some(PathBuf::from("out/annotated.xml")));
                assert_eq!(args.source_root, PathBuf::from("/work"));
                assert_eq!(args.duplicates, complexity::Duplicates::Keep);
                assert_eq!(args.rules, complexity::Rules::Mccabe);
                assert_eq!(args.unmatched, complexity::Unmatched::Fail);
                assert!(args.no_rollup && args.exclude_tests && args.dry_run);
            }
            other => panic!("expected Complexity, got {other:?}"),
        }
    }

    #[test]
    fn complexity_rejects_an_unknown_rule_set() {
        let err = Cli::try_parse_from(["jci-coverage", "complexity", "--rules", "cognitive"])
            .unwrap_err();
        assert!(err.to_string().contains("rules"), "{err}");
    }

    #[test]
    fn complexity_reads_or_writes_a_baseline_but_not_both() {
        let cli = Cli::try_parse_from([
            "jci-coverage",
            "complexity",
            "--max-complexity",
            "15",
            "--baseline",
            "b.tsv",
        ])
        .expect("parses");
        match cli.command {
            Commands::Complexity(args) => {
                assert_eq!(args.baseline, Some(PathBuf::from("b.tsv")));
                assert_eq!(args.write_baseline, None);
            }
            other => panic!("expected Complexity, got {other:?}"),
        }
        let err = Cli::try_parse_from([
            "jci-coverage",
            "complexity",
            "--baseline",
            "a",
            "--write-baseline",
            "b",
        ])
        .unwrap_err();
        assert!(err.to_string().contains("cannot be used with"), "{err}");
    }

    #[test]
    fn the_baseline_options_default_to_a_file_in_the_directory_it_runs_from() {
        let parse = |extra: &[&str]| {
            let mut argv = vec!["jci-coverage", "complexity"];
            argv.extend_from_slice(extra);
            match Cli::try_parse_from(argv).expect("parses").command {
                Commands::Complexity(args) => (args.baseline, args.write_baseline),
                other => panic!("expected Complexity, got {other:?}"),
            }
        };
        let default = Some(PathBuf::from(".jci-coverage-baseline"));
        assert_eq!(complexity::DEFAULT_BASELINE, ".jci-coverage-baseline");
        assert_eq!(parse(&[]), (None, None), "off unless asked for");
        assert_eq!(parse(&["--baseline"]), (default.clone(), None));
        assert_eq!(parse(&["--write-baseline"]), (None, default.clone()));
        assert_eq!(
            parse(&["--baseline", "ci/b.bin"]),
            (Some(PathBuf::from("ci/b.bin")), None)
        );
        assert_eq!(
            parse(&["--write-baseline=ci/b.bin"]),
            (None, Some(PathBuf::from("ci/b.bin")))
        );
        assert_eq!(
            parse(&["--baseline", "--max-complexity", "15"]),
            (default, None),
            "a bare flag does not swallow the next option"
        );
        let err = Cli::try_parse_from([
            "jci-coverage",
            "complexity",
            "--baseline",
            "--write-baseline",
        ])
        .unwrap_err();
        assert!(err.to_string().contains("cannot be used with"), "{err}");
    }

    #[test]
    fn complexity_takes_a_summary_file() {
        let cli = Cli::try_parse_from(["jci-coverage", "complexity", "--summary-file", "out/s.md"])
            .expect("parses");
        match cli.command {
            Commands::Complexity(args) => {
                assert_eq!(args.summary_file, Some(PathBuf::from("out/s.md")));
            }
            other => panic!("expected Complexity, got {other:?}"),
        }
    }

    #[test]
    fn complexity_posts_a_pr_comment_only_when_asked() {
        let parse = |extra: &[&str]| {
            let mut argv = vec!["jci-coverage", "complexity"];
            argv.extend(extra);
            match Cli::try_parse_from(argv).expect("parses").command {
                Commands::Complexity(args) => args,
                other => panic!("expected Complexity, got {other:?}"),
            }
        };
        assert!(!parse(&[]).pr_comment);
        assert!(parse(&["--pr-comment"]).pr_comment);
    }

    #[test]
    fn recording_a_baseline_excludes_the_options_that_have_nothing_to_do_there() {
        for other in [
            ["--baseline", "b.bin"],
            ["--summary-file", "s.md"],
            ["--pr-comment", ""],
        ] {
            let mut argv = vec!["jci-coverage", "complexity", "--write-baseline", "w.bin"];
            argv.extend(other.iter().filter(|a| !a.is_empty()));
            let err = Cli::try_parse_from(argv).expect_err(other[0]).to_string();
            assert!(err.contains("cannot be used with"), "{}: {err}", other[0]);
        }
    }

    #[test]
    fn check_only_cannot_be_combined_with_an_output_file() {
        let cli = Cli::try_parse_from(["jci-coverage", "complexity", "--check-only"]).expect("ok");
        match cli.command {
            Commands::Complexity(args) => assert!(args.check_only),
            other => panic!("expected Complexity, got {other:?}"),
        }
        let err = Cli::try_parse_from([
            "jci-coverage",
            "complexity",
            "--check-only",
            "--output",
            "o.xml",
        ])
        .unwrap_err();
        assert!(err.to_string().contains("cannot be used with"), "{err}");
    }

    #[test]
    fn every_subcommand_has_a_long_about_distinct_from_its_about() {
        use clap::CommandFactory;
        let cmd = Cli::command();
        for name in ["complexity", "upload"] {
            let sub = cmd
                .find_subcommand(name)
                .unwrap_or_else(|| panic!("no '{name}' subcommand"));
            let about = sub.get_about().map(ToString::to_string);
            let long_about = sub.get_long_about().map(ToString::to_string);
            assert!(
                long_about.is_some() && long_about != about,
                "'{name}': long_about must be set and differ from about (about: {about:?})"
            );
        }
    }

    #[test]
    fn unknown_subcommand_is_error() {
        assert!(Cli::try_parse_from(["jci-coverage", "bogus"]).is_err());
    }

    /// The orb generator reads `--help`, and takes a wrapped line that begins
    /// with `--` for a flag, so prose must not wrap onto one.
    #[test]
    fn help_prose_never_wraps_onto_a_line_that_looks_like_a_flag() {
        use clap::CommandFactory;
        let mut cmd = Cli::command();
        for name in ["complexity", "upload"] {
            let sub = cmd.find_subcommand_mut(name).expect("subcommand");
            let longs: Vec<String> = sub
                .get_arguments()
                .filter_map(|a| a.get_long().map(|l| format!("--{l}")))
                .collect();
            let help = sub.render_long_help().to_string();
            for line in help.lines().map(str::trim_start) {
                if line.starts_with("--") {
                    let flag = line.split([' ', ',', '=']).next().unwrap_or("");
                    assert!(
                        longs.iter().any(|l| l == flag) || flag == "--help",
                        "'{name}' help has a prose line starting with {flag}: {line}"
                    );
                }
            }
        }
    }
}
